function splitIntoChunks(text) {
  return text
    .trim()
    .split(/\n\s*\n/)
    .map((paragraph) => paragraph.trim())
    .filter(Boolean);
}

function estimateDuration(text) {
  const words = text.trim().split(/\s+/).length;

  // Slow bedtime narration estimate.
  const seconds = Math.max(30, Math.round((words / 105) * 60));

  return seconds;
}

function formatTime(seconds) {
  const safeSeconds = Math.max(0, Math.floor(seconds));
  const minutes = Math.floor(safeSeconds / 60);
  const remaining = safeSeconds % 60;

  return `${minutes}:${String(remaining).padStart(2, "0")}`;
}

export default function JaySleep() {
  const navigate = useNavigate();

  const [selectedStory, setSelectedStory] = useState(null);
  const [isPlaying, setIsPlaying] = useState(false);
  const [isPaused, setIsPaused] = useState(false);
  const [elapsed, setElapsed] = useState(0);
  const [currentParagraph, setCurrentParagraph] = useState(0);
  const [voiceName, setVoiceName] = useState("");

  const speechChunksRef = useRef([]);
  const speechIndexRef = useRef(0);
  const stoppedRef = useRef(false);
  const timerRef = useRef(null);
  const nextSpeechRef = useRef(null);

  const [voices, setVoices] = useState([]);

  useEffect(() => {
    if (!("speechSynthesis" in window)) {
      return;
    }

    const loadVoices = () => {
      const availableVoices =
        window.speechSynthesis.getVoices();

      setVoices(availableVoices);

      const preferred =
        availableVoices.find(
          (voice) =>
            voice.lang === "en-US" &&
            /Natural|Google|Microsoft|David|Mark|Jenny/i.test(
              voice.name
            )
        ) ||
        availableVoices.find(
          (voice) => voice.lang === "en-US"
        ) ||
        availableVoices.find(
          (voice) =>
            voice.lang &&
            voice.lang.toLowerCase().startsWith("en")
        ) ||
        availableVoices[0];

      if (preferred) {
        setVoiceName(preferred.name);
      }
    };

    loadVoices();

    window.speechSynthesis.onvoiceschanged =
      loadVoices;

    return () => {
      window.speechSynthesis.onvoiceschanged = null;
      window.speechSynthesis.cancel();
    };
  }, []);

  useEffect(() => {
    return () => {
      stopEverything();
    };
  }, []);

  const clearTimers = () => {
    if (timerRef.current) {
      clearInterval(timerRef.current);
      timerRef.current = null;
    }

    if (nextSpeechRef.current) {
      clearTimeout(nextSpeechRef.current);
      nextSpeechRef.current = null;
    }
  };

  const stopEverything = () => {
    stoppedRef.current = true;

    clearTimers();

    if ("speechSynthesis" in window) {
      window.speechSynthesis.cancel();
      window.speechSynthesis.resume();
    }

    speechChunksRef.current = [];
    speechIndexRef.current = 0;

    setIsPlaying(false);
    setIsPaused(false);
  };

  const getBestVoice = () => {
    const available =
      voices.length > 0
        ? voices
        : window.speechSynthesis.getVoices();

    return (
      available.find(
        (voice) =>
          voice.lang === "en-US" &&
          /Natural|Google|Microsoft|David|Mark|Jenny/i.test(
            voice.name
          )
      ) ||
      available.find(
        (voice) => voice.lang === "en-US"
      ) ||
      available.find(
        (voice) =>
          voice.lang &&
          voice.lang.toLowerCase().startsWith("en")
      ) ||
      available[0] ||
      null
    );
  };

  const speakParagraph = (story, index) => {
    if (
      stoppedRef.current ||
      !story ||
      !("speechSynthesis" in window)
    ) {
      return;
    }

    const chunks = speechChunksRef.current;

    if (
      !chunks.length ||
      index >= chunks.length
    ) {
      clearTimers();

      setIsPlaying(false);
      setIsPaused(false);
      setCurrentParagraph(chunks.length);

      return;
    }

    speechIndexRef.current = index;
    setCurrentParagraph(index);

    const utterance =
      new SpeechSynthesisUtterance(
        chunks[index]
      );

    /*
     * JAY'S BEDTIME VOICE
     *
     * Lower rate = slower and calmer.
     * Pitch slightly below normal = softer male-style tone
     * when the selected system voice supports it.
     */
    utterance.lang = "en-US";
    utterance.rate = 0.72;
    utterance.pitch = 0.88;
    utterance.volume = 1.0;

    const voice = getBestVoice();

    if (voice) {
      utterance.voice = voice;
    }

    utterance.onstart = () => {
      console.log("🔊 Jay is speaking:", chunks[index]);

      setIsPlaying(true);
      setIsPaused(false);
    };

    utterance.onend = () => {
      if (stoppedRef.current) {
        return;
      }

      nextSpeechRef.current = setTimeout(() => {
        speakParagraph(
          story,
          index + 1
        );
      }, 500);
    };

    utterance.onerror = (event) => {
      console.error(
        "Jay Speech Error:",
        event.error
      );

      if (
        event.error === "interrupted" ||
        event.error === "canceled"
      ) {
        return;
      }

      setIsPlaying(false);
      setIsPaused(false);
    };

    /*
     * IMPORTANT FOR CHROME / EDGE:
     * resume before speak prevents SpeechSynthesis
     * from staying stuck in a paused state.
     */
    window.speechSynthesis.resume();

    window.speechSynthesis.speak(
      utterance
    );
  };

  const startStory = (story) => {
    if (!("speechSynthesis" in window)) {
      alert(
        "Jay's voice is not supported in this browser. Please use Google Chrome or Microsoft Edge."
      );

      return;
    }

    /*
     * This function is called directly from the
     * Start Story button, which is important because
     * browsers allow speech more reliably after a
     * real user interaction.
     */
    stopEverything();

    stoppedRef.current = false;

    const chunks = splitIntoChunks(
      story.text
    );

    speechChunksRef.current = chunks;
    speechIndexRef.current = 0;

    setSelectedStory(story);
    setElapsed(0);
    setCurrentParagraph(0);
    setIsPlaying(true);
    setIsPaused(false);

    /*
     * Start elapsed timer.
     */
    timerRef.current = setInterval(() => {
      setElapsed((previous) => {
        const duration =
          estimateDuration(story.text);

        if (previous >= duration) {
          return duration;
        }

        return previous + 1;
      });
    }, 1000);

    /*
     * Get voices again immediately.
     */
    const availableVoices =
      window.speechSynthesis.getVoices();

    if (availableVoices.length > 0) {
      setVoices(availableVoices);
    }

    /*
     * Start Jay speaking.
     *
     * Small delay gives Chrome time to
     * initialize the speech engine after
     * the click.
     */
    setTimeout(() => {
      if (stoppedRef.current) {
        return;
      }

      window.speechSynthesis.cancel();
      window.speechSynthesis.resume();

      speakParagraph(story, 0);
    }, 100);
  };

  const pauseStory = () => {
    if (
      !("speechSynthesis" in window) ||
      !isPlaying
    ) {
      return;
    }

    window.speechSynthesis.pause();

    setIsPaused(true);
  };

  const resumeStory = () => {
    if (
      !("speechSynthesis" in window) ||
      !isPlaying
    ) {
      return;
    }

    window.speechSynthesis.resume();

    setIsPaused(false);
  };

  const restartStory = () => {
    if (selectedStory) {
      startStory(selectedStory);
    }
  };

  const stopStory = () => {
    stopEverything();
    setElapsed(0);
    setCurrentParagraph(0);
  };

  const closeReader = () => {
    stopEverything();

    setSelectedStory(null);
    setElapsed(0);
    setCurrentParagraph(0);
  };

  const goBackToJay = () => {
    stopEverything();

    /*
     * Change this ONLY if your Jay page uses
     * a different route.
     */
    navigate("/jay");
  };

  const progress =
    selectedStory
      ? Math.min(
          100,
          (elapsed /
            estimateDuration(
              selectedStory.text
            )) *
            100
        )
      : 0;

  return (
    <main className="jay-sleep-page">
      <div className="jay-sleep-stars" />

      <button
        type="button"
        className="jay-back-button"
        onClick={goBackToJay}
      >
        ← Back to Jay
      </button>

      <header className="jay-sleep-header">
        <div className="jay-moon">🌙</div>

        <h1>Jay's Sleep Stories</h1>

        <p>
          Relax, listen, and drift into a peaceful
          gaming adventure.
        </p>
      </header>

      {!selectedStory && (
        <>
          <section className="jay-story-grid">
            {stories.map((story) => (
              <article
                className="jay-story-card"
                key={story.id}
              >
                <div className="jay-story-icon">
                  {story.emoji}
                </div>

                <h2>{story.title}</h2>

                <div className="jay-story-duration">
                  ◷ 2–3 min
                </div>

                <div className="jay-story-category">
                  {story.category}
                </div>

                <button
                  type="button"
                  className="jay-start-button"
                  onClick={() =>
                    startStory(story)
                  }
                >
                  ▶ Start Story
                </button>
              </article>
            ))}
          </section>

          <footer className="jay-sleep-footer">
            <span />
            <p>♥ Sweet dreams with Jay</p>
            <span />
          </footer>
        </>
      )}

      {selectedStory && (
        <section className="jay-reader">
          <button
            type="button"
            className="jay-close-reader"
            onClick={closeReader}
            aria-label="Close story"
          >
            ×
          </button>

          <div className="jay-reader-icon">
            {selectedStory.emoji}
          </div>

          <h2>{selectedStory.title}</h2>

          <div className="jay-reader-category">
            {selectedStory.category}
          </div>

          <div className="jay-progress-area">
            <div className="jay-progress-bar">
              <div
                className="jay-progress-fill"
                style={{
                  width: `${progress}%`,
                }}
              />
            </div>

            <div className="jay-time-row">
              <span>
                {formatTime(elapsed)}
              </span>

              <span>
                {formatTime(
                  estimateDuration(
                    selectedStory.text
                  )
                )}
              </span>
            </div>
          </div>

          <div className="jay-story-text">
            {splitIntoChunks(
              selectedStory.text
            ).map((paragraph, index) => (
              <p
                key={index}
                className={
                  index === currentParagraph &&
                  isPlaying
                    ? "jay-speaking-paragraph"
                    : ""
                }
              >
                {paragraph}
              </p>
            ))}
          </div>

          <div className="jay-controls">
            {!isPlaying ? (
              <button
                type="button"
                className="jay-control-button primary"
                onClick={() =>
                  startStory(selectedStory)
                }
              >
                ▶ Play
              </button>
            ) : isPaused ? (
              <button
                type="button"
                className="jay-control-button primary"
                onClick={resumeStory}
              >
                ▶ Resume
              </button>
            ) : (
              <button
                type="button"
                className="jay-control-button primary"
                onClick={pauseStory}
              >
                ⏸ Pause
              </button>
            )}

            <button
              type="button"
              className="jay-control-button"
              onClick={stopStory}
            >
              ■ Stop
            </button>

            <button
              type="button"
              className="jay-control-button"
              onClick={restartStory}
            >
              ↻ Restart
            </button>
          </div>

          <div className="jay-speaking-status">
            {isPlaying && !isPaused ? (
              <>
                <span className="jay-sound-icon">
                  🔊
                </span>
                Jay is reading your story...
              </>
            ) : isPaused ? (
              <>
                <span className="jay-sound-icon">
                  ⏸
                </span>
                Jay is taking a little pause...
              </>
            ) : (
              <>
                <span className="jay-sound-icon">
                  🔇
                </span>
                Story paused
              </>
            )}
          </div>

          {voiceName && (
            <div className="jay-voice-info">
              Voice: {voiceName}
            </div>
          )}

          <button
            type="button"
            className="jay-reader-back"
            onClick={closeReader}
          >
            ← Back to Sleep Stories
          </button>
        </section>
      )}
    </main>
  );
}